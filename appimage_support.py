"""Runtime fixes that only apply when mymc runs from its AppImage.

The AppImage bundles the fontconfig library from Ubuntu 22.04.  That
older library can't fully understand the font configuration of newer
distributions, and then fails to find glyphs (Japanese save titles show
up as boxes).  So, inside the AppImage, mymc uses its own small fontconfig
file: it looks for fonts in the usual system folders plus the fonts
bundled in the AppImage, without reading the host's newer config rules.

The file must name the AppImage's mount point, which changes on every
run, so it's written at start-up, before wx (and fontconfig) is loaded.
"""

import os

_FONTS_CONF = """<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- Generated by mymc for its AppImage; rewritten on every start. -->
<fontconfig>
	<dir>/usr/share/fonts</dir>
	<dir>/usr/local/share/fonts</dir>
	<dir prefix="xdg">fonts</dir>
	<dir>~/.fonts</dir>
	<dir>{bundled}</dir>
	<cachedir prefix="xdg">mymc/fontconfig</cachedir>
	<!-- Variable CJK fonts (e.g. Fedora's NotoSansCJK-VF.ttc) render as
	     empty boxes with the older FreeType in the AppImage. -->
	<selectfont>
		<rejectfont>
			<glob>*CJK*-VF.*</glob>
			<glob>*CJK*VF.*</glob>
		</rejectfont>
	</selectfont>
{aliases}
	<match target="font">
		<edit name="antialias" mode="assign"><bool>true</bool></edit>
		<edit name="hinting" mode="assign"><bool>true</bool></edit>
		<edit name="hintstyle" mode="assign"><const>hintslight</const></edit>
	</match>
</fontconfig>
"""

_FAMILIES = {
	"sans-serif": ["Noto Sans", "Cantarell", "Ubuntu", "DejaVu Sans",
		       "Liberation Sans", "Noto Sans CJK JP",
		       "Droid Sans Fallback"],
	"serif": ["Noto Serif", "DejaVu Serif", "Liberation Serif",
		  "Noto Serif CJK JP", "Droid Sans Fallback"],
	"monospace": ["Noto Sans Mono", "DejaVu Sans Mono",
		      "Liberation Mono", "Droid Sans Fallback"],
}
_FAMILIES["Sans"] = _FAMILIES["sans-serif"]
_FAMILIES["Serif"] = _FAMILIES["serif"]
_FAMILIES["Monospace"] = _FAMILIES["monospace"]


def _xml_escape(s):
	return (s.replace("&", "&amp;").replace("<", "&lt;")
		.replace(">", "&gt;"))


def configure_fonts():
	"""Point fontconfig at a config file that works inside the AppImage.

	Does nothing outside the AppImage, or when the user has set
	FONTCONFIG_FILE themselves."""

	appdir = os.environ.get("APPDIR")
	if not appdir or os.environ.get("FONTCONFIG_FILE"):
		return
	bundled = os.path.join(appdir, "usr", "share", "fonts")
	if not os.path.isdir(bundled):
		return
	aliases = "\n".join(
		"\t<alias><family>%s</family><prefer>%s</prefer></alias>"
		% (name, "".join("<family>%s</family>" % f for f in fams))
		for name, fams in _FAMILIES.items())
	conf = _FONTS_CONF.format(bundled = _xml_escape(bundled),
				  aliases = aliases)
	cache = os.environ.get("XDG_CACHE_HOME") or os.path.expanduser("~/.cache")
	path = os.path.join(cache, "mymc", "fonts.conf")
	try:
		os.makedirs(os.path.dirname(path), exist_ok = True)
		with open(path, "w", encoding = "utf-8") as f:
			f.write(conf)
	except OSError:
		return		# keep the default configuration
	os.environ["FONTCONFIG_FILE"] = path
